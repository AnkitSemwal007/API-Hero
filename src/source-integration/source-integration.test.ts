test('hover uses protocol metadata and does not expose secrets', () => {
  const hover = formatRequestHover(
    request({
      id: 'request:a#0',
      name: 'Get User',
      method: 'GET',
      url: '/users/1?access_token=super-secret-token',
      protocol: 'http',
      sourceRef: 'src/services/user.ts',
    }),
  );
  assert.equal(hover.title, 'GET /users/1');
  assert.match(hover.body, /Name: Get User/u);
  assert.match(hover.body, /Protocol: HTTP/u);
  assert.match(hover.body, /Source: src\/services\/user\.ts/u);
  assert.doesNotMatch(hover.body, /super-secret-token/u);
  assert.doesNotMatch(hover.title, /super-secret-token/u);
  assert.doesNotMatch(hover.body, /Authorization/u);

  const unlabeled = formatRequestHover(
    request({
      id: 'request:b#0',
      name: 'GET /users/1?access_token=super-secret-token',
      method: 'GET',
      url: '/users/1?access_token=super-secret-token',
    }),
  );
  assert.equal(unlabeled.title, 'GET /users/1');
  assert.match(unlabeled.body, /Name: GET \/users\/1$/mu);
  assert.doesNotMatch(unlabeled.body, /super-secret-token/u);
  assert.doesNotMatch(unlabeled.title, /access_token/u);

  const graphql = formatRequestHover(
    request({
      id: 'request:g#0',
      name: 'GetUser',
      method: 'POST',
      url: '/graphql',
      protocol: 'graphql',
    }),
  );
  assert.equal(graphql.title, 'POST /graphql');
  assert.match(graphql.body, /Protocol: GraphQL/u);
});

test('type insertion detects duplicate names and does not overwrite', () => {
  const existing = 'export interface User {\n  id: number;\n}\n';
  assert.deepEqual(collidingGeneratedTypeNames(['User'], existing), ['User']);
  assert.deepEqual(collidingGeneratedTypeNames(['Account'], existing), []);
  assert.ok(collectExportedTypeNames(existing).has('User'));
  const inserted = prepareGeneratedTypeInsertion(existing, 'export interface Account {}\n');
  assert.match(inserted, /export interface User/u);
  assert.match(inserted, /export interface Account/u);
  assert.equal(existing.includes('Account'), false);
});

test('open .api overlays keep stable request ids for id mapping', () => {
  const filePath = 'file:///ws/Collections/Demo/Get-User.api';
  const id = requestIdFor(filePath, 0);
  const catalog = catalogFromWorkspace(undefined, [
    {
      filePath,
      workspaceRootPath: 'file:///ws',
      relativePath: 'Collections/Demo/Get-User.api',
      text: '@name Get User\nGET /users\n',
    },
  ]);
  assert.equal(catalog.requests[0]?.id, id);
  const resolved = catalog.resolveFromAnnotations(
    [{ kind: 'id', value: id }],
    { sourceFilePath: 'file:///ws/src/user.ts', workspaceRoots: ['file:///ws'] },
  );
  assert.equal(resolved.kind, 'match');
  if (resolved.kind === 'match') {
    assert.equal(resolved.request.name, 'Get User');
  }
});
