test('multi-root: unique path maps; duplicate names across roots do not', () => {
  const catalog = buildSourceIntegrationCatalog([
    request({
      id: 'request:a#0',
      name: 'Health',
      workspaceRootPath: 'file:///ws-a',
      filePath: 'file:///ws-a/Collections/Demo/Health.api',
      relativePath: 'Collections/Demo/Health.api',
    }),
    request({
      id: 'request:b#0',
      name: 'Health',
      workspaceRootPath: 'file:///ws-b',
      filePath: 'file:///ws-b/Collections/Other/Health.api',
      relativePath: 'Collections/Other/Health.api',
    }),
  ]);
  const byName = catalog.resolveFromAnnotations(
    [{ kind: 'name', value: 'Health' }],
    {
      sourceFilePath: 'file:///ws-a/src/app.ts',
      workspaceRoots: ['file:///ws-a', 'file:///ws-b'],
    },
  );
  assert.equal(byName.kind, 'ambiguous');

  const byPath = catalog.resolveFromAnnotations(
    [{ kind: 'request', value: 'Collections/Demo/Health.api' }],
    {
      sourceFilePath: 'file:///ws-a/src/app.ts',
      workspaceRoots: ['file:///ws-a', 'file:///ws-b'],
    },
  );
  assert.equal(byPath.kind, 'match');
  if (byPath.kind === 'match') {
    assert.equal(byPath.request.id, 'request:a#0');
  }
});

test('path plus name disambiguates a multi-request .api file', () => {
  const catalog = buildSourceIntegrationCatalog([
    request({
      id: 'request:file#0',
      name: 'List Users',
      filePath: 'file:///ws/Collections/Demo/users.api',
      relativePath: 'Collections/Demo/users.api',
      requestIndex: 0,
    }),
    request({
      id: 'request:file#1',
      name: 'Get User',
      filePath: 'file:///ws/Collections/Demo/users.api',
      relativePath: 'Collections/Demo/users.api',
      requestIndex: 1,
      range: range(8),
    }),
  ]);
  const pathOnly = catalog.resolveFromAnnotations(
    [{ kind: 'request', value: 'Collections/Demo/users.api' }],
    { sourceFilePath: 'file:///ws/src/user.ts', workspaceRoots: ['file:///ws'] },
  );
  assert.equal(pathOnly.kind, 'ambiguous');

  const disambiguated = catalog.resolveFromAnnotations(
    [
      { kind: 'request', value: 'Collections/Demo/users.api' },
      { kind: 'name', value: 'Get User' },
    ],
    { sourceFilePath: 'file:///ws/src/user.ts', workspaceRoots: ['file:///ws'] },
  );
  assert.equal(disambiguated.kind, 'match');
  if (disambiguated.kind === 'match') {
    assert.equal(disambiguated.request.id, 'request:file#1');
  }
});

test('source → .api mapping uses the catalog request file path', () => {
  const mapped = request({ id: 'request:a#0', name: 'Get User' });
  const catalog = buildSourceIntegrationCatalog([mapped]);
  const resolved = catalog.resolveFromAnnotations(
    [{ kind: 'name', value: 'Get User' }],
    { sourceFilePath: 'file:///ws/src/user.ts', workspaceRoots: ['file:///ws'] },
  );
  assert.equal(resolved.kind, 'match');
  if (resolved.kind === 'match') {
    assert.equal(resolved.request.filePath, mapped.filePath);
  }
});

