import type { Range } from '../parser/types';

function range(line: number): Range {
  return {
    start: { line, column: 0, offset: line * 10 },
    end: { line, column: 3, offset: line * 10 + 3 },
  };
}

function request(
  overrides: Partial<CatalogRequest> & Pick<CatalogRequest, 'id' | 'name'>,
): CatalogRequest {
  return {
    filePath: `file:///ws/Collections/Demo/${overrides.name.replace(/\s+/gu, '-')}.api`,
    relativePath: `Collections/Demo/${overrides.name.replace(/\s+/gu, '-')}.api`,
    workspaceRootPath: 'file:///ws',
    requestIndex: 0,
    method: 'GET',
    url: '/users',
    protocol: 'http',
    range: range(2),
    ...overrides,
  };
}

test('parses explicit @api-hero annotations and ignores unannotated calls', () => {
  const sites = parseSourceAnnotations(
    [
      '// @api-hero name: Get User',
      'const response = await api.getUser(id)',
      '',
      'const other = await api.listUsers()',
    ].join('\n'),
  );
  assert.equal(sites.length, 1);
  assert.equal(sites[0]?.line, 1);
  assert.deepEqual(sites[0]?.annotations, [
    { kind: 'name', value: 'Get User' },
  ]);
});

test('parses request path, JSDoc, and generated-file header annotations', () => {
  const sites = parseSourceAnnotations(
    [
      '/**',
      ' * Generated by API Hero.',
      ' * @api-hero name: Get User',
      ' * @api-hero request: Collections/Demo/Get-User.api',
      ' */',
      'export interface GetUser {}',
    ].join('\n'),
  );
  assert.equal(sites.length, 1);
  assert.equal(sites[0]?.line, 5);
  assert.equal(sites[0]?.annotations.length, 2);
  assert.equal(sites[0]?.annotations[0]?.kind, 'name');
  assert.equal(sites[0]?.annotations[1]?.kind, 'request');
});

test('bare .api path is a request annotation; bare text is a name', () => {
  const sites = parseSourceAnnotations(
    [
      '// @api-hero Collections/Demo/Get-User.api',
      'export const run = () => undefined',
      '// @api-hero Get User',
      'export const named = () => undefined',
    ].join('\n'),
  );
  assert.equal(sites[0]?.annotations[0]?.kind, 'request');
  assert.equal(sites[1]?.annotations[0]?.kind, 'name');
});

test('parses hash comments, camelCase JSDoc, and id annotations', () => {
  const sites = parseSourceAnnotations(
    [
      '# @api-hero name: Get User',
      'const fromHash = await api.getUser()',
      '/**',
      ' * @apiHero id: request:a#0',
      ' */',
      'export interface GetUser {}',
    ].join('\n'),
  );
  assert.equal(sites.length, 2);
  assert.deepEqual(sites[0]?.annotations, [{ kind: 'name', value: 'Get User' }]);
  assert.deepEqual(sites[1]?.annotations, [{ kind: 'id', value: 'request:a#0' }]);
});

test('CodeLens appears only for a uniquely matching API', () => {
  const catalog = buildSourceIntegrationCatalog([
    request({ id: 'request:a#0', name: 'Get User' }),
  ]);
  const lenses = createSourceFileCodeLensDescriptors(
    '// @api-hero Get User\nconst response = await api.getUser(id)\n',
    catalog,
    { sourceFilePath: 'file:///ws/src/user.ts', workspaceRoots: ['file:///ws'] },
  );
  assert.equal(lenses.length, 3);
  assert.equal(lenses[0]?.command.id, COMMAND_IDS.runRequest);
  assert.equal(lenses[1]?.command.id, COMMAND_IDS.openApiDefinition);
  assert.equal(lenses[2]?.command.id, COMMAND_IDS.generateTypeScript);
});

